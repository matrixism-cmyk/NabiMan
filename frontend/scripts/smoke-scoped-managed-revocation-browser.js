const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
let stage = 'startup';
(async () => {
 const fixture = JSON.parse(fs.readFileSync(0, 'utf8'));
 const origin = new URL(process.argv[2]).origin;
 const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
 const errors = [];
 try {
  async function pageFor(token, role) {
   const page = await browser.newPage({ viewport: { width: 1440, height: 1200 } });
   page.on('pageerror', () => errors.push('Page error'));
   page.on('request', req => { if (req.url().includes(token) || req.url().includes('token=')) errors.push('Credential URL'); });
   await page.addInitScript(({ token, role, origin }) => { if (window.top !== window || window.location.origin !== origin) return; sessionStorage.setItem('nabiman_token', token); sessionStorage.setItem('nabiman_role', role); localStorage.setItem('nabiman_lang', 'ko'); }, { token, role, origin });
   await page.goto(origin + '/#mec/mecTenants');
   if (role === 'admin') await page.getByRole('row').filter({ hasText: fixture.tenant_id }).click();
   return page;
  }
  stage = 'grant-only-delegation';
  const root = await pageFor(fixture.admin_token, 'admin');
  await root.getByRole('button', { name: '외부 프로젝트 회원', exact: true }).click();
  const policyForm = root.locator('form').filter({ has: root.getByRole('button', { name: '위임 정책 저장', exact: true }) });
  await policyForm.getByLabel('위임 활성화', { exact: true }).check();
  await policyForm.getByRole('checkbox', { name: /^scope-manager/ }).check();
  await policyForm.getByLabel('위임 만료일 (지금부터 최대 30일)', { exact: true }).fill(new Date(Date.now() + 86400000).toISOString().slice(0, 16));
  await policyForm.getByLabel('위임 변경 사유', { exact: true }).fill('하위 회원의 읽기 권한 부여만 먼저 위임합니다');
  await policyForm.getByLabel('현재 tenant ID를 입력해 확인', { exact: true }).fill(fixture.tenant_id);
  await policyForm.getByLabel('위임 대상·역할 범위·만료일과 기존 권한 유지 조건을 검토했습니다.', { exact: true }).check();
  if (await policyForm.getByLabel('관리 중인 직접 연결 회수 허용 (전체 접근 차단과 구분)', { exact: true }).isChecked()) throw new Error('Revocation implicitly enabled');
  const policyResponse = root.waitForResponse(r => r.url().endsWith('/access-delegation') && r.request().method() === 'PUT');
  await policyForm.getByRole('button', { name: '위임 정책 저장', exact: true }).click();
  const policy = await policyResponse; const savedPolicy = (await policy.json()).data;
  if (policy.status() !== 200 || savedPolicy.allowed_actions.join(',') !== 'grant') throw new Error('Grant-only policy invalid');
  stage = 'scoped-grant';
  const manager = await pageFor(fixture.token, 'viewer');
  await manager.getByRole('row').filter({ hasText: fixture.tenant_id }).getByRole('button', { name: '외부 권한 관리', exact: true }).click();
  const form = manager.locator('form').filter({ has: manager.getByRole('button', { name: '관리되는 외부 권한 부여', exact: true }) });
  await form.getByLabel('권한을 부여할 승인 회원', { exact: true }).selectOption(fixture.local_id);
  await form.getByLabel('권한 부여 사유', { exact: true }).fill('승인된 하위 회원에게 읽기 권한과 소속 정책 회수 설정');
  await form.getByRole('checkbox').nth(0).check(); await form.getByRole('checkbox').nth(1).check();
  const grantResponse = manager.waitForResponse(r => r.url().endsWith('/managed-memberships') && r.request().method() === 'POST');
  await form.getByRole('button', { name: '관리되는 외부 권한 부여', exact: true }).click();
  const grant = await grantResponse; const receipt = (await grant.json()).data;
  if (grant.status() !== 201 || !receipt?.binding_id) throw new Error('Managed grant failed');
  stage = 'scoped-ledger-without-revoke';
  const ledger = manager.getByRole('heading', { name: '회원별 관리 중인 외부 연결', exact: true }).locator('xpath=../..');
  const summary = ledger.locator('summary').filter({ hasText: 'identity-fixture' });
  await summary.waitFor(); await summary.click();
  if (await ledger.getByRole('button', { name: '이 관리 연결 회수', exact: true }).count()) throw new Error('Grant-only policy offers revocation');
  const list = await manager.request.get(origin + `/api/mec/v1/tenants/${fixture.tenant_id}/scoped-managed-memberships`, { headers: { Authorization: `Bearer ${fixture.token}` } });
  const rows = (await list.json()).data;
  if (list.status() !== 200 || list.headers()['cache-control'] !== 'no-store' || rows.length !== 1 || rows[0].can_revoke !== false || rows[0].source_access_currently_allowed !== true) throw new Error('Scoped ledger invalid');
  const revokeBody = { confirm_operation_id: receipt.operation_id, expected_binding_id: receipt.binding_id, expected_updated_at: rows[0].ownership_updated_at, expected_delegation_version: savedPolicy.version, reason: 'Review direct owned binding only', acknowledge_direct_binding_only: true };
  const revokeUrl = origin + `/api/mec/v1/tenants/${fixture.tenant_id}/managed-memberships/${receipt.operation_id}/revoke`;
  const denied = await manager.request.post(revokeUrl, { headers: { Authorization: `Bearer ${fixture.token}` }, data: revokeBody });
  if (denied.status() !== 403) throw new Error('Grant-only approval allows revocation');
  stage = 'explicit-revocation-delegation';
  await policyForm.getByLabel('관리 중인 직접 연결 회수 허용 (전체 접근 차단과 구분)', { exact: true }).check();
  await policyForm.getByLabel('위임 변경 사유', { exact: true }).fill('정확한 소유 연결에 한정한 회수를 별도로 승인합니다');
  await policyForm.getByLabel('현재 tenant ID를 입력해 확인', { exact: true }).fill(fixture.tenant_id);
  await policyForm.getByLabel('위임 대상·역할 범위·만료일과 기존 권한 유지 조건을 검토했습니다.', { exact: true }).check();
  const updateResponse = root.waitForResponse(r => r.url().endsWith('/access-delegation') && r.request().method() === 'PUT');
  await policyForm.getByRole('button', { name: '위임 정책 저장', exact: true }).click();
  const update = await updateResponse; const updated = (await update.json()).data;
  if (update.status() !== 200 || !updated.allowed_actions.includes('revoke') || updated.version === savedPolicy.version) throw new Error('Explicit revocation approval invalid');
  const stale = await manager.request.post(revokeUrl, { headers: { Authorization: `Bearer ${fixture.token}` }, data: revokeBody });
  if (stale.status() !== 409) throw new Error('Stale approval can revoke');
  const refreshed = manager.waitForResponse(r => r.url().endsWith('/scoped-managed-memberships'));
  await ledger.getByRole('button', { name: '새로고침', exact: true }).click();
  if ((await (await refreshed).json()).data[0].can_revoke !== true) throw new Error('Revocation approval not observed');
  stage = 'reviewed-revocation';
  const revokeForm = ledger.locator('form').filter({ has: manager.getByRole('button', { name: '이 관리 연결 회수', exact: true }) });
  await revokeForm.getByLabel('연결 회수 사유', { exact: true }).fill('이 관리 연결의 직접 부재만 확인하고 회수합니다');
  const revokeButton = revokeForm.getByRole('button', { name: '이 관리 연결 회수', exact: true });
  if (await revokeButton.isEnabled()) throw new Error('Revoke lacks exact confirmation');
  await revokeForm.getByLabel('위의 관리 연결 생성 요청 ID를 입력해 확인', { exact: true }).fill(receipt.operation_id);
  await revokeForm.getByRole('checkbox').check();
  await revokeForm.screenshot({ path: path.resolve(__dirname, '../../screenshots/scoped-managed-revocation.png') });
  const revokedResponse = manager.waitForResponse(r => r.url().endsWith('/revoke') && r.request().method() === 'POST');
  await revokeButton.click(); const revoked = await revokedResponse; const result = (await revoked.json()).data;
  if (revoked.status() !== 200 || revoked.headers()['cache-control'] !== 'no-store' || result?.direct_binding_absence_confirmed !== true || result?.all_external_access_revoked !== false || result?.grant_operation_id !== receipt.operation_id) throw new Error('Revocation receipt not confirmed');
  await summary.getByText(/직접 연결 부재 확인됨/).waitFor();
  const final = await manager.request.get(origin + `/api/mec/v1/tenants/${fixture.tenant_id}/scoped-managed-memberships`, { headers: { Authorization: `Bearer ${fixture.token}` } });
  const finalRows = (await final.json()).data;
  if (finalRows[0].ownership_state !== 'revoked' || finalRows[0].source_access_currently_allowed !== true || finalRows[0].can_revoke !== false) throw new Error('Revocation changed source policy or remained mutable');
  const repeated = await manager.request.post(revokeUrl, { headers: { Authorization: `Bearer ${fixture.token}` }, data: { ...revokeBody, expected_delegation_version: updated.version } });
  if (repeated.status() !== 409) throw new Error('Revocation can be replayed');
  const inventory = await root.request.get(origin + `/api/mec/v1/tenants/${fixture.tenant_id}/members`, { headers: { Authorization: `Bearer ${fixture.admin_token}` } });
  const bindings = (await inventory.json()).data;
  if (bindings.some(b => b.user_id === fixture.remote_id) || !bindings.some(b => b.role_template === 'project-owner')) throw new Error('Unrelated binding changed');
  await ledger.screenshot({ path: path.resolve(__dirname, '../../screenshots/scoped-managed-ledger.png') });
  if (errors.length) throw new Error('Browser error or credential URL');
  process.stdout.write('PASS: scoped ownership ledger, grant-only approval denies revocation, separate explicit revocation approval, stale version denial, exact reviewed UI revocation, direct-only receipt, preserved source policy and unrelated bindings, no delete replay.\n');
 } finally { await browser.close(); }
})().catch(() => { process.stderr.write('Scoped managed revocation browser smoke failed at ' + stage + '\n'); process.exitCode = 1; });
